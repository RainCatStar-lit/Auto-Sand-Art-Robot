#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""G-code 生成：线段 → G1/G0 移动 + M106/M107 出沙控制。"""

from typing import List, Tuple

Segment = Tuple[Tuple[float, float], Tuple[float, float]]


def segments_to_gcode(
    segments: List[Segment],
    scale: float = 1.0,
    feed_mm_min: float = 1500.0,
    flow_pwm: int = 128,
    safe_z: float = 2.0,
    work_z: float = 0.0,
) -> List[str]:
    """
    将线段列表转换为 G-code 指令列表。

    沙画机器人特殊指令：
      M106 S<pwm>   开沙（电磁阀开，PWM 控制流量）
      M107          停沙（电磁阀关）

    参数：
      segments: 线段列表 [((x1,y1),(x2,y2)), ...]
      scale: 像素转毫米的比例
      feed_mm_min: 出沙进给速度 (mm/min)
      flow_pwm: 出沙 PWM 占空比 (0-255)，对应标定表中的流量
      safe_z: 抬笔/停沙时的 Z 高度（沙画机器人可用作逻辑抬笔）
      work_z: 出沙时的 Z 高度
    """
    gcode: List[str] = []

    # 文件头
    gcode.append("; Auto-Sand-Art-Robot G-code")
    gcode.append("; Generated by img2gcode MVP")
    gcode.append("G21 ; 单位毫米")
    gcode.append("G90 ; 绝对坐标")
    gcode.append("G92 X0 Y0 Z0 ; 归零当前位置")
    gcode.append("")

    # 初始：停沙，移动到安全高度
    gcode.append("M107 ; 初始停沙")
    gcode.append(f"G0 X0 Y0 Z{safe_z:.2f} F{feed_mm_min * 2} ; 安全抬笔")

    for i, ((x1, y1), (x2, y2)) in enumerate(segments):
        # 移动到线段起点（空跑，停沙）
        gcode.append(
            f"G0 X{x1 * scale:.2f} Y{y1 * scale:.2f} F{feed_mm_min * 2} ; 空跑到段起点"
        )

        # 开沙
        gcode.append(f"M106 S{flow_pwm} ; 开沙 PWM={flow_pwm}")

        # 出沙移动到线段终点
        gcode.append(
            f"G1 X{x2 * scale:.2f} Y{y2 * scale:.2f} F{feed_mm_min} ; 出沙绘制"
        )

    # 结束：停沙，回原点
    gcode.append("M107 ; 最终停沙")
    gcode.append(f"G0 X0 Y0 Z{safe_z:.2f} F{feed_mm_min * 2} ; 返回原点")
    gcode.append("M84 ; 关闭步进电机")

    return gcode


def write_gcode(gcode: List[str], output_path: str):
    """将 G-code 列表写入文件。"""
    with open(output_path, "w", encoding="utf-8") as f:
        for line in gcode:
            f.write(line + "\n")